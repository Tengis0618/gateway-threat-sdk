// React Native has no process.env at runtime, so this writes the GATEWAY_* values from
// .env.local (or the shell, which wins) into env.generated.ts. That file is git-ignored.
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const keys = [
    "GATEWAY_API_KEY",
    "GATEWAY_ENVIRONMENT",
    "GATEWAY_BASE_URL",
    "GATEWAY_HEADER_PREFIX",
    "GATEWAY_WEB_CHECKOUT_URL",
];

function readEnvFile(file) {
    if (!fs.existsSync(file)) return {};
    const values = {};
    for (const line of fs.readFileSync(file, "utf8").split("\n")) {
        const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
        if (match) values[match[1]] = match[2].replace(/^(['"])(.*)\1$/, "$2");
    }
    return values;
}

const fromFile = readEnvFile(path.join(root, ".env.local"));
const env = Object.fromEntries(keys.map((key) => [key, process.env[key] ?? fromFile[key] ?? ""]));

fs.writeFileSync(
    path.join(root, "env.generated.ts"),
    `// Generated by scripts/generate-env.js. Do not edit or commit.\nexport const env = ${JSON.stringify(env, null, 4)};\n`,
);

if (!env.GATEWAY_BASE_URL) {
    console.warn("GATEWAY_BASE_URL is not set. Copy .env.example to .env.local and fill it in.");
}
